/**
 * lib/assetprompt.mjs —— 素材提示词模板（2026-11-07）
 * ============================================================================
 * 问题：三视图 / 场景图一直让 agent 自己写，出来的提示词又短又业余
 *       （"一个年轻女生，三视图" → 模型只能瞎猜版式、光线、比例）。
 *
 * 做法：把两套专业模板固化在插件里，agent 只填角色名/外貌/服装/场景，
 *       版式、光线、镜头、材质、禁止项由模板保证。
 *
 * 为什么模板要这么长：豆包对"版式词"（三栏/分割线/色卡）和"摄影词"
 * （柔光箱/85mm/浅景深）敏感，写全了才稳定；写"三视图"三个字它只给个拼贴。
 * ============================================================================
 */

const NO_TEXT = '画面不出现任何文字、字幕、水印、logo、签名'

/** 角色三视图（设定卡式排版） */
export function roleSheetPrompt({ name, appearance, outfit, style, extra = '' }) {
  return [
    `竖版角色设定图（2:3），${style || '3D 动漫（非写实），日系 Q 版三头身'}。`,
    `角色：${name}。外貌：${appearance}。服装：${outfit}。`,
    '版式：纯白无影背景，极简杂志排版；画面三分栏——',
    '左栏竖排小字信息位（留白，不要写真字），中栏为同一角色的三视图全身立绘，右栏为 3 格表情头像。',
    '三视图要求：正面 / 正侧面 / 背面，同一人、同一服装、同一光位，标准站姿，全身入画，脚底对齐同一条水平线，',
    '头身比一致，肩线水平，手臂自然下垂，五指分开清晰可见。',
    '表情格：平静 / 微笑 / 惊讶，同一张脸，妆发服装完全一致。',
    '光线：柔光箱均匀打光，无硬阴影，无投影，整体曝光一致。',
    '材质：PBR 次世代质感，皮肤有次表面散射，布料有细微纹理，金属配饰有环境反射。',
    '镜头：85mm 等效，轻微长焦压缩，无透视畸变，主体占画面高度 90%。',
    '一致性清单（逐项核对，三视图之间必须完全一致）：发型与发长、耳朵/犄角/尾巴的位置与朝向、',
    '五官比例、服装款式与配色、配饰位置、身高与头身比。任何一项只能有一种正确答案。',
    '禁止：多手指、断肢、肢体粘连、脸崩、头身比不一致、服装三视图之间不一致、',
    `背景杂物、地面阴影、${NO_TEXT}。`,
    extra,
  ].filter(Boolean).join('')
}

/** 干净参考图（白底单人，才能当 reference 用） */
export function roleRefPrompt({ name, appearance, outfit, style, extra = '' }) {
  return [
    `单人全身参考图（2:3），${style || '3D 动漫（非写实），日系 Q 版三头身'}。`,
    `角色：${name}。外貌：${appearance}。服装：${outfit}。`,
    '要求：纯白背景、无任何道具与文字、单人正面站立、双手自然下垂、双脚并拢、',
    '全身完整入画（头顶留 5% 白边，脚底留 5% 白边），面向镜头但视线平视。',
    '光线：正面柔光，均匀无影；材质与配色与角色设定卡完全一致。',
    '禁止：裁剪到脚踝或头顶、姿势夸张、背景渐变、',
    `${NO_TEXT}。`,
    extra,
  ].filter(Boolean).join('')
}

/** 场景图（空镜，不带人物） */
export function scenePrompt({ name, timeOfDay, weather, style, extra = '' }) {
  return [
    `空场景图（竖版 2:3），${style || '3D 动漫（非写实）'}，画面中**没有任何人物**。`,
    `场景：${name}。时间：${timeOfDay || '傍晚'}。天气/空气感：${weather || '薄雾'}。`,
    '构图：平视机位，一点透视，画面留出足够的中景表演空间（中央 60% 不要被家具挡住）。',
    '层次：前景（虚化的枝叶/栏杆）— 中景（主体空间）— 远景（天际线或建筑轮廓），三层分明。',
    '光线：单一主光源定方向，冷暖对比明确；有明确的明暗交界与投影方向，避免平光。',
    '材质：PBR 写实材质，地面有湿润反射或灰尘颗粒，墙面有使用痕迹（不干净但统一）。',
    '禁止：人物、动物、车辆主体、',
    `${NO_TEXT}。`,
    extra,
  ].filter(Boolean).join('')
}

/** 按 kind 分派 */
export function assetPrompt(kind, opts = {}) {
  const k = String(kind || '').toLowerCase()
  if (k === 'role' || k === 'sheet' || k === '三视图') return roleSheetPrompt(opts)
  if (k === 'ref' || k === 'reference' || k === '参考图') return roleRefPrompt(opts)
  if (k === 'scene' || k === '场景' || k === '场景图') return scenePrompt(opts)
  throw new Error(`未知素材类型：${kind}（role / ref / scene）`)
}
